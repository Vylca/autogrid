export function tFor(l, key, params = {}) {
  const dict = dictionaries[l] || fr;
  let v = dict[key] ?? fr[key];
  if (v === undefined) return key;
  if (typeof v === 'object') {
    const n = Number(params.n);
    const one = l === 'fr' ? n <= 1 : n === 1;
    v = one ? v.one : v.other;
  }
  return v.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

export function t(key, params) {
  return tFor(lang.value, key, params);
}

export function formatDateFor(l, iso) {
  if (!iso) return '';
  const d = new Date(`${iso}T12:00:00`);
  if (Number.isNaN(d.getTime())) return iso;
  return new Intl.DateTimeFormat(l === 'en' ? 'en-GB' : 'fr-FR', { day: 'numeric', month: 'long', year: 'numeric' }).format(d);
}

export function formatDate(iso) {
  return formatDateFor(lang.value, iso);
}
